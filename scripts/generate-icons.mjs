// Generates src/components/ui/icons.tsx: the Phosphor icons this app uses, in only the weights it uses.
// Each icon in @phosphor-icons/react ships all six weights; keeping one or two saves ~12 KB gzipped.
//
// To add an icon or weight: edit ICONS, then run `npm run icons`.
// The first weight listed is the default when a component doesn't pass `weight`.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const ICONS = {
  AppleLogo: ["fill"],
  ArrowClockwise: ["bold"],
  ArrowDown: ["bold"],
  ArrowLeft: ["bold"],
  ArrowSquareOut: ["bold"],
  Bank: ["bold"],
  CaretRight: ["regular"],
  Check: ["bold"],
  CheckCircle: ["fill"],
  Circle: ["fill"],
  Clock: ["regular"],
  Copy: ["bold"],
  CreditCard: ["bold"],
  ExclamationMark: ["bold"],
  Flask: ["bold"],
  GoogleLogo: ["bold"],
  IdentificationCard: ["regular", "bold"],
  Info: ["regular", "fill"],
  List: ["regular"],
  LockSimple: ["fill"],
  PencilSimple: ["regular"],
  ScanSmiley: ["regular"],
  SealCheck: ["fill"],
  ShieldCheck: ["fill"],
  Warning: ["fill"],
  WarningCircle: ["fill"],
  XCircle: ["fill"],
};

const require = createRequire(import.meta.url);
const defsDir = join(dirname(require.resolve("@phosphor-icons/react/package.json")), "dist", "defs");

/** The JSX for one weight, read from Phosphor's compiled definition. */
function weightJsx(name, weight) {
  const source = readFileSync(join(defsDir, `${name}.es.js`), "utf8");
  const entry = source.match(new RegExp(`\\[\\s*"${weight}",([\\s\\S]*?)\\n  \\]`));
  if (!entry) throw new Error(`${name} has no "${weight}" weight`);
  const elements = [...entry[1].matchAll(/createElement\("(\w+)", \{([^}]*)\}\)/g)].map(([, tag, attrs]) => {
    const props = [...attrs.matchAll(/(\w+): "([^"]*)"/g)].map(([, key, value]) => `${key}="${value}"`).join(" ");
    return `<${tag} ${props} />`;
  });
  if (!elements.length) throw new Error(`Couldn't read ${name} (${weight})`);
  return elements.length === 1 ? elements[0] : `<>${elements.join("")}</>`;
}

const lines = Object.entries(ICONS).map(([name, weights]) => {
  const map = weights.map((w) => `${w}: ${weightJsx(name, w)}`).join(", ");
  return `export const ${name}Icon = icon("${name}Icon", { ${map} });`;
});

const out = `// Generated by scripts/generate-icons.mjs. Edit the list there and run \`npm run icons\`.
// Phosphor icons in only the weights this app uses (the package ships six per icon).

import IconBase from "@phosphor-icons/react/dist/lib/IconBase";
import type { IconProps, IconWeight } from "@phosphor-icons/react/dist/lib/types";
import type { ReactElement } from "react";

function icon<W extends IconWeight>(name: string, weights: Record<W, ReactElement>) {
  const map = new Map(Object.entries(weights)) as Map<IconWeight, ReactElement>;
  const fallback = Object.keys(weights)[0] as W;
  const Icon = ({ weight, ...props }: Omit<IconProps, "weight"> & { weight?: W }) => <IconBase {...props} weight={weight ?? fallback} weights={map} />;
  Icon.displayName = name;
  return Icon;
}

${lines.join("\n")}
`;

writeFileSync(new URL("../src/components/ui/icons.tsx", import.meta.url), out);
console.log(`Wrote ${lines.length} icons to src/components/ui/icons.tsx`);
